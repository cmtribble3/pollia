// Imported verbatim from PolRAY's PolRayPostprocess/Metal/ColorMapping.h.
// Preserve table order (including PolRAY's reversed Viridis) and linear interpolation.
// These tables supply both the Metal image mapping and the SwiftUI colorbar.
public enum DisplayColorMap: UInt32, CaseIterable, Sendable, Identifiable {
    case turbo, viridis, phase, diverging, grayscale, seismic
    public var id: Self { self }
    public var title: String {
        switch self {
        case .turbo: "Turbo"
        case .viridis: "Viridis"
        case .phase: "Phase"
        case .diverging: "Diverging"
        case .grayscale: "Grayscale"
        case .seismic: "Seismic"
        }
    }

    public var colors: [SIMD3<Float>] {
        switch self {
        case .turbo: Self.turboColors
        case .viridis: Self.viridisColors
        case .phase: Self.phaseColors
        case .diverging: Self.divergingColors
        case .grayscale: [SIMD3(repeating: 0), SIMD3(repeating: 1)]
        // Keep pollia's existing blue/white/red palette as an additional Q/U/V option.
        case .seismic: [SIMD3(0.12, 0.3, 0.8), SIMD3(repeating: 1), SIMD3(0.8, 0.15, 0.1)]
        }
    }

    public func color(at position: Float) -> SIMD3<Float> {
        let samples = colors
        let index = min(1, max(0, position)) * Float(samples.count - 1)
        let lower = Int(index)
        let upper = min(lower + 1, samples.count - 1)
        return samples[lower] + (samples[upper] - samples[lower]) * (index - Float(lower))
    }

    // Generate Metal constants from the same data used by the colorbar.
    static var metalSource: String {
        var source = "#include <metal_stdlib>\nusing namespace metal;\n"
        for map in allCases {
            let values = map.colors.map { "float3(\($0.x), \($0.y), \($0.z))" }.joined(separator: ",\n")
            source += "constant float3 palette\(map.rawValue)[\(map.colors.count)] = {\(values)};\n"
        }
        source += "float3 display_colormap(float t, uint palette) { t = saturate(t); switch (palette) {\n"
        for map in allCases {
            source += "case \(map.rawValue): { float index = t * \(map.colors.count - 1).0; uint i = uint(floor(index)); return mix(palette\(map.rawValue)[i], palette\(map.rawValue)[min(i + 1, \(map.colors.count - 1)u)], index - float(i)); }\n"
        }
        return source + "default: return float3(t); } }\n"
    }

